def expected_outputs():
    """Build all output text in memory; malformed inputs never partially render."""
    source=(ROOT/'docs/execution-sequence.mmd').read_text(encoding='utf-8')
    if source.lstrip().partition('\n')[0].strip()!='sequenceDiagram':
        raise ValueError('docs/execution-sequence.mmd must start with sequenceDiagram')
    outputs={ROOT/name:updated_block(ROOT/name,source) for name in BLOCK_TARGETS}
    arch=architecture()
    outputs[ROOT/'docs/images/architecture.svg']=arch
    outputs[ROOT/'docs/execution-sequence.md']=sequence_markdown(source)
    outputs[ROOT/'docs/index.html']=viewer(arch,source)
    for path in outputs:
        if not path.parent.is_dir():
            raise ValueError(f'Missing generated output directory: {path.parent}')
    return outputs


def render(check=False):
    outputs=expected_outputs()
    if check:
        stale=[path.relative_to(ROOT).as_posix() for path,content in outputs.items()
               if not path.is_file() or path.read_bytes()!=content.encode('utf-8')]
        if stale:
            raise ValueError('Generated documentation is out of sync: '+', '.join(stale))
        return
    for path,content in outputs.items():
        data=content.encode('utf-8')
        if not path.is_file() or path.read_bytes()!=data:
            path.write_bytes(data)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Validate generated outputs without writing files')
    args=parser.parse_args(argv)
    try:
        render(check=args.check)
    except (OSError,ValueError) as exc:
        parser.exit(1,f'{exc}\n')
    print('Generated documentation is synchronized' if args.check else 'Rendered icon architecture and synchronized native Mermaid documentation')


if __name__=='__main__':main()
