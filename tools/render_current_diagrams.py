def updated_block(path,source):
    """Validate exactly one ordered marker pair before changing any output."""
    if not path.is_file():
        raise ValueError(f'Missing Mermaid block target: {path}')
    contents=path.read_text(encoding='utf-8')
    if contents.count(BEGIN)!=1 or contents.count(END)!=1:
        raise ValueError(f'Expected exactly one BEGIN/END marker pair: {path}')
    start,end=contents.index(BEGIN),contents.index(END)
    if end<start:
        raise ValueError(f'Mermaid markers are reversed: {path}')
    block=BEGIN+'\n'+GENERATED+'\n```mermaid\n'+source.rstrip()+'\n```\n'+END
    return contents[:start]+block+contents[end+len(END):]


def update_block(path,source):
    """Update one validated block; rendering preflights all targets together."""
    contents=updated_block(path,source)
    path.write_text(contents,encoding='utf-8',newline='\n')


